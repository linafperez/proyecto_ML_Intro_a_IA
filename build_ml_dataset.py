from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split


# -----------------------------------------------------------------------------
# Configuration
# -----------------------------------------------------------------------------
INPUT_CSV = Path("data/processed/features/segmentation_features.csv")  # Input CSV generated by the segmentation pipeline.
OUTPUT_DIR = Path("data/processed/ml_ready")  # Folder where ML-ready files will be saved.
RANDOM_STATE = 42  # Random seed used to make the train/validation split reproducible.
VALIDATION_SIZE = 0.20  # Fraction of valid images assigned to validation/testing.


# Warnings are evaluated in this priority order. If an image has several active
# warnings, it is discarded only once using the first active warning in this list.
WARNING_PRIORITY = [
    "warning_empty_mask",
    "warning_too_large_mask",
    "warning_tissue_almost_empty",
    "warning_too_many_components",
    "warning_selected_empty_but_raw_not_empty",
    "warning_central_fallback_used",
]


# Descriptive names used in reports instead of technical warning names.
WARNING_DESCRIPTIONS = {
    "warning_empty_mask": "sin cromatina segmentada",
    "warning_too_large_mask": "máscara de cromatina demasiado grande",
    "warning_tissue_almost_empty": "tejido casi vacío",
    "warning_too_many_components": "demasiados componentes/células segmentadas",
    "warning_selected_empty_but_raw_not_empty": "selección final vacía aunque la máscara cruda no estaba vacía",
    "warning_central_fallback_used": "selección central realizada por fallback",
}


# Columns that must never be used as ML features.
EXPLICITLY_EXCLUDED_COLUMNS = {
    "image_id",
    "source_csv_image_id",
    "image_path",
    "final_label",
    "numeric_label",
    "numeric_label_for_ml",
    "processing_status",
    "filename",
    "coordinateX",
    "coordinateY",
    "Tumor",
    "Scanner",
    "Origin",
    "Species",
}


# -----------------------------------------------------------------------------
# Helper functions
# -----------------------------------------------------------------------------
def fail(message):
    # Stop execution with a clear error message.
    raise SystemExit(f"ERROR: {message}")


def is_warning_active(value):
    # Convert different possible warning representations into a Boolean value.
    if pd.isna(value):
        return False

    if isinstance(value, (bool, np.bool_)):
        return bool(value)

    if isinstance(value, (int, float, np.integer, np.floating)):
        return value != 0

    value_as_text = str(value).strip().lower()
    return value_as_text in {"true", "1", "yes", "y", "t", "active"}


def get_image_column(dataframe):
    # Find the column that contains image names.
    if "image_id" in dataframe.columns:
        return "image_id"

    if "source_csv_image_id" in dataframe.columns:
        return "source_csv_image_id"

    fail("No image identifier column was found. Expected 'image_id' or 'source_csv_image_id'.")


def build_numeric_label_column(dataframe):
    # Build a numeric label vector for ML without printing intermediate messages.
    if "numeric_label" in dataframe.columns:
        numeric_labels = pd.to_numeric(dataframe["numeric_label"], errors="coerce")
        return numeric_labels, "numeric_label", {}

    if len(dataframe.columns) < 2:
        fail("'numeric_label' does not exist and the CSV does not have a second column to use as label.")

    fallback_label_column = dataframe.columns[1]
    raw_labels = dataframe[fallback_label_column]
    numeric_labels = pd.to_numeric(raw_labels, errors="coerce")

    non_empty_mask = raw_labels.notna() & (raw_labels.astype(str).str.strip() != "")
    numeric_success_mask = numeric_labels.notna() | ~non_empty_mask

    if numeric_success_mask.all():
        return numeric_labels, fallback_label_column, {}

    normalized_labels = raw_labels.astype(str).str.strip().str.upper()
    known_label_map = {
        "NMF": 0,
        "AMF": 1,
        "NORMAL": 0,
        "ATYPICAL": 1,
        "ATYPICAL MITOSIS": 1,
        "NORMAL MITOSIS": 0,
    }

    unique_labels = sorted(normalized_labels[non_empty_mask].unique().tolist())

    if set(unique_labels).issubset(set(known_label_map.keys())):
        numeric_labels = normalized_labels.map(known_label_map)
        used_mapping = {label: known_label_map[label] for label in unique_labels}
        return numeric_labels, fallback_label_column, used_mapping

    if len(unique_labels) >= 2:
        automatic_label_map = {label: index for index, label in enumerate(unique_labels)}
        numeric_labels = normalized_labels.map(automatic_label_map)
        return numeric_labels, fallback_label_column, automatic_label_map

    fail(
        "'numeric_label' does not exist and the second column could not be converted "
        "or mapped into numeric labels."
    )


def convert_labels_to_numpy(label_series):
    # Convert valid labels to a NumPy array, preserving integer class labels when possible.
    label_values = label_series.to_numpy(dtype=float)

    if np.allclose(label_values, np.round(label_values)):
        return label_values.astype(int)

    return label_values


def get_warning_columns(dataframe):
    # Build the warning column list using the requested priority first.
    existing_priority_warnings = [column for column in WARNING_PRIORITY if column in dataframe.columns]
    extra_warning_columns = [
        column
        for column in dataframe.columns
        if column.startswith("warning_") and column not in existing_priority_warnings
    ]
    return existing_priority_warnings + sorted(extra_warning_columns)


def get_first_active_warning(row, warning_columns):
    # Return the first active warning according to the defined priority.
    for warning_column in warning_columns:
        if is_warning_active(row[warning_column]):
            return warning_column
    return np.nan


def build_warning_reports(dataframe, image_column, warning_columns, first_warning_column):
    # Create summary and detailed reports for images discarded by warnings.
    summary_rows = []
    detail_rows = []

    for warning_column in warning_columns:
        reason = WARNING_DESCRIPTIONS.get(
            warning_column,
            warning_column.replace("warning_", "").replace("_", " "),
        )

        discarded_mask = first_warning_column == warning_column
        discarded_images = dataframe.loc[discarded_mask, image_column].astype(str).tolist()

        summary_rows.append(
            {
                "numero_de_descartadas": len(discarded_images),
                "motivo_de_descarte": reason,
                "imagenes_descartadas": "; ".join(discarded_images),
            }
        )

        for image_name in discarded_images:
            detail_rows.append(
                {
                    "image_id": image_name,
                    "discard_reason": reason,
                    "technical_warning_name": warning_column,
                }
            )

    summary_dataframe = pd.DataFrame(
        summary_rows,
        columns=["numero_de_descartadas", "motivo_de_descarte", "imagenes_descartadas"],
    )
    detail_dataframe = pd.DataFrame(
        detail_rows,
        columns=["image_id", "discard_reason", "technical_warning_name"],
    )

    return summary_dataframe, detail_dataframe


def select_feature_columns(dataframe, label_column, image_column):
    # Features used for ML:
    # All numeric columns remaining after removing image identifiers, labels,
    # metadata, processing status columns and warning columns.
    excluded_columns = set(EXPLICITLY_EXCLUDED_COLUMNS)
    excluded_columns.add(label_column)
    excluded_columns.add(image_column)

    candidate_columns = [
        column
        for column in dataframe.columns
        if column not in excluded_columns and not column.startswith("warning_")
    ]

    feature_columns = []

    for column in candidate_columns:
        converted_column = pd.to_numeric(dataframe[column], errors="coerce")
        original_non_empty_mask = dataframe[column].notna() & (dataframe[column].astype(str).str.strip() != "")
        converted_success_mask = converted_column.notna() | ~original_non_empty_mask

        if converted_success_mask.all():
            feature_columns.append(column)

    if len(feature_columns) == 0:
        fail("No numeric feature columns were found after excluding identifiers, labels, metadata and warnings.")

    return feature_columns


def class_counts_from_labels(label_values, label_names=None):
    # Count samples per class using final_label when available, otherwise numeric labels.
    if label_names is not None:
        series = pd.Series(label_names).astype(str)
    else:
        series = pd.Series(label_values).astype(str)

    counts = series.value_counts(dropna=False)
    preferred_order = ["NMF", "AMF", "NORMAL", "ATYPICAL"]
    ordered_items = []

    for label_name in preferred_order:
        if label_name in counts.index:
            ordered_items.append((label_name, int(counts.loc[label_name])))

    for label_name, count in counts.items():
        if label_name not in preferred_order:
            ordered_items.append((label_name, int(count)))

    return ordered_items


def create_label_mapping_dataframe(used_label_mapping, valid_dataset):
    # Save the relation between textual labels and numeric labels when it can be inferred.
    mapping_rows = []

    if used_label_mapping:
        for label_name, numeric_value in sorted(used_label_mapping.items(), key=lambda item: item[1]):
            mapping_rows.append({"label_name": label_name, "numeric_label": numeric_value})
    elif "final_label" in valid_dataset.columns:
        grouped = valid_dataset.groupby("numeric_label")["final_label"].unique()
        for numeric_value, labels in grouped.items():
            label_text = "; ".join(sorted(str(label) for label in labels))
            mapping_rows.append({"label_name": label_text, "numeric_label": numeric_value})
    else:
        for numeric_value in sorted(valid_dataset["numeric_label"].unique()):
            mapping_rows.append({"label_name": str(numeric_value), "numeric_label": numeric_value})

    return pd.DataFrame(mapping_rows, columns=["label_name", "numeric_label"])


def can_use_balanced_stratified_split(y_values, validation_count):
    # Check whether each class can appear in both training and validation.
    unique_labels, class_counts = np.unique(y_values, return_counts=True)
    number_of_classes = len(unique_labels)
    training_count = len(y_values) - validation_count

    if number_of_classes < 2:
        return False

    if class_counts.min() < 2:
        return False

    if validation_count < number_of_classes:
        return False

    if training_count < number_of_classes:
        return False

    return True


def compute_validation_counts_per_class(y_values, validation_count):
    # Allocate validation samples per class using largest-remainder rounding.
    unique_labels, class_counts = np.unique(y_values, return_counts=True)
    exact_counts = class_counts * (validation_count / len(y_values))
    validation_counts = np.floor(exact_counts).astype(int)

    # Every class should have at least one validation sample and one training sample.
    validation_counts = np.maximum(validation_counts, 1)
    validation_counts = np.minimum(validation_counts, class_counts - 1)

    while validation_counts.sum() < validation_count:
        available = np.where(validation_counts < (class_counts - 1))[0]
        if len(available) == 0:
            break

        remainders = exact_counts - np.floor(exact_counts)
        best_position = available[np.argmax(remainders[available])]
        validation_counts[best_position] += 1

    while validation_counts.sum() > validation_count:
        available = np.where(validation_counts > 1)[0]
        if len(available) == 0:
            break

        remainders = exact_counts - np.floor(exact_counts)
        best_position = available[np.argmin(remainders[available])]
        validation_counts[best_position] -= 1

    return dict(zip(unique_labels, validation_counts))


def balanced_stratified_split_indices(y_values):
    # Create a reproducible split that keeps all possible classes in both sets.
    total_samples = len(y_values)
    validation_count = int(np.ceil(total_samples * VALIDATION_SIZE))

    if validation_count <= 0 or validation_count >= total_samples:
        fail("The validation size produced an empty training or validation set.")

    indices = np.arange(total_samples)
    rng = np.random.default_rng(RANDOM_STATE)

    if not can_use_balanced_stratified_split(y_values, validation_count):
        training_indices, validation_indices = train_test_split(
            indices,
            test_size=VALIDATION_SIZE,
            random_state=RANDOM_STATE,
            shuffle=True,
            stratify=None,
        )
        return training_indices, validation_indices, "random split; stratified split was not possible"

    validation_counts_by_class = compute_validation_counts_per_class(y_values, validation_count)

    training_indices_list = []
    validation_indices_list = []

    for class_value in sorted(validation_counts_by_class.keys()):
        class_indices = indices[y_values == class_value]
        shuffled_class_indices = rng.permutation(class_indices)

        class_validation_count = int(validation_counts_by_class[class_value])
        validation_indices_list.extend(shuffled_class_indices[:class_validation_count])
        training_indices_list.extend(shuffled_class_indices[class_validation_count:])

    training_indices = rng.permutation(np.array(training_indices_list, dtype=int))
    validation_indices = rng.permutation(np.array(validation_indices_list, dtype=int))

    return training_indices, validation_indices, "balanced stratified split by class"


def print_compact_summary(
    total_rows,
    warning_summary_dataframe,
    valid_dataset,
    X,
    y,
    training_dataset,
    validation_dataset,
    X_training,
    X_validation,
    split_method,
    output_dir,
):
    # Print only the final compact summary requested by the user.
    total_valid = len(valid_dataset)
    total_discarded = total_rows - total_valid

    print("\n================ ML DATASET SUMMARY ================")
    print(f"Total images read: {total_rows}")
    print(f"Accepted valid images: {total_valid}")
    print(f"Discarded images: {total_discarded}")

    nonzero_warning_summary = warning_summary_dataframe[
        warning_summary_dataframe["numero_de_descartadas"] > 0
    ]

    print("\nDiscarded images by reason:")
    if nonzero_warning_summary.empty:
        print("  None")
    else:
        for _, row in nonzero_warning_summary.iterrows():
            print(f"  {row['motivo_de_descarte']}: {row['numero_de_descartadas']}")

    label_names = valid_dataset["final_label"].to_numpy() if "final_label" in valid_dataset.columns else None
    print("\nAccepted images by class:")
    for label_name, count in class_counts_from_labels(y, label_names):
        print(f"  {label_name}: {count}")

    print("\nDataset arrays:")
    print(f"  X: {X.shape[0]} images x {X.shape[1]} features")
    print(f"  y: {y.shape[0]} labels")

    training_label_names = (
        training_dataset["final_label"].to_numpy()
        if "final_label" in training_dataset.columns
        else None
    )
    validation_label_names = (
        validation_dataset["final_label"].to_numpy()
        if "final_label" in validation_dataset.columns
        else None
    )

    print("\nTrain/validation split:")
    print(f"  Method: {split_method}")
    print(f"  Training images: {len(training_dataset)}")
    for label_name, count in class_counts_from_labels(training_dataset["numeric_label"].to_numpy(), training_label_names):
        print(f"    {label_name}: {count}")

    print(f"  Validation images: {len(validation_dataset)}")
    for label_name, count in class_counts_from_labels(validation_dataset["numeric_label"].to_numpy(), validation_label_names):
        print(f"    {label_name}: {count}")

    print(f"  X_training: {X_training.shape[0]} images x {X_training.shape[1]} features")
    print(f"  X_validation: {X_validation.shape[0]} images x {X_validation.shape[1]} features")

    print("\nFiles saved in:")
    print(f"  {output_dir}/")
    print("    - X.npy, y.npy, valid_image_names.npy")
    print("    - X_training.npy, y_training.npy, training_image_names.npy")
    print("    - X_validation.npy, y_validation.npy, validation_image_names.npy")
    print("    - ml_dataset.csv, valid_images.csv")
    print("    - training_dataset.csv, validation_dataset.csv")
    print("    - feature_names.csv, label_mapping.csv")
    print("    - discarded_by_warning.csv, discarded_images_detail.csv")
    print("====================================================\n")


# -----------------------------------------------------------------------------
# Main pipeline
# -----------------------------------------------------------------------------
def main():
    # Verify input CSV.
    if not INPUT_CSV.exists():
        fail(f"Input file not found: {INPUT_CSV}")

    # Create output directory.
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Read segmentation features.
    dataframe = pd.read_csv(INPUT_CSV)
    total_rows = len(dataframe)

    if total_rows == 0:
        fail("The input CSV is empty.")

    # Identify image and label columns.
    image_column = get_image_column(dataframe)
    numeric_labels, label_column, used_label_mapping = build_numeric_label_column(dataframe)

    # Find warning columns and assign one discard reason per image.
    warning_columns = get_warning_columns(dataframe)

    if len(warning_columns) > 0:
        first_warning = dataframe.apply(
            lambda row: get_first_active_warning(row, warning_columns),
            axis=1,
        )
    else:
        first_warning = pd.Series(np.nan, index=dataframe.index)

    warning_free_mask = first_warning.isna()

    # Build and save warning discard reports.
    warning_summary_dataframe, warning_detail_dataframe = build_warning_reports(
        dataframe=dataframe,
        image_column=image_column,
        warning_columns=warning_columns,
        first_warning_column=first_warning,
    )

    warning_summary_dataframe.to_csv(OUTPUT_DIR / "discarded_by_warning.csv", index=False)
    warning_detail_dataframe.to_csv(OUTPUT_DIR / "discarded_images_detail.csv", index=False)

    # Select numeric feature columns for X.
    feature_columns = select_feature_columns(
        dataframe=dataframe,
        label_column=label_column,
        image_column=image_column,
    )
    feature_dataframe = dataframe[feature_columns].apply(pd.to_numeric, errors="coerce")

    # Build validity masks.
    if "processing_status" in dataframe.columns:
        processing_success_mask = dataframe["processing_status"].astype(str).str.strip().str.lower() == "success"
    else:
        processing_success_mask = pd.Series(True, index=dataframe.index)

    valid_label_mask = numeric_labels.notna()
    valid_features_mask = feature_dataframe.notna().all(axis=1)

    valid_mask = processing_success_mask & warning_free_mask & valid_label_mask & valid_features_mask

    if valid_mask.sum() == 0:
        fail("No valid images remain after filtering by processing status, warnings, labels and numeric features.")

    # Construct final ML-ready arrays.
    valid_features = feature_dataframe.loc[valid_mask, feature_columns]
    valid_labels = numeric_labels.loc[valid_mask]
    valid_image_names = dataframe.loc[valid_mask, image_column].astype(str).to_numpy()

    X = valid_features.to_numpy(dtype=float)
    y = convert_labels_to_numpy(valid_labels)

    if len(y) < 2:
        fail("Not enough valid images to split into training and validation sets. At least 2 valid images are required.")

    # Build reviewable complete dataset.
    valid_metadata_parts = [
        pd.Series(valid_image_names, name="image_id"),
        pd.Series(y, name="numeric_label"),
    ]

    if "final_label" in dataframe.columns:
        valid_metadata_parts.append(
            dataframe.loc[valid_mask, "final_label"].reset_index(drop=True).rename("final_label")
        )

    valid_metadata = pd.concat(valid_metadata_parts, axis=1)

    valid_dataset = pd.concat(
        [valid_metadata.reset_index(drop=True), valid_features.reset_index(drop=True)],
        axis=1,
    )

    # Save complete ML dataset.
    np.save(OUTPUT_DIR / "X.npy", X)
    np.save(OUTPUT_DIR / "y.npy", y)
    np.save(OUTPUT_DIR / "valid_image_names.npy", valid_image_names)

    pd.DataFrame({"feature_name": feature_columns}).to_csv(OUTPUT_DIR / "feature_names.csv", index=False)
    valid_dataset.to_csv(OUTPUT_DIR / "ml_dataset.csv", index=False)
    valid_dataset.to_csv(OUTPUT_DIR / "valid_images.csv", index=False)

    label_mapping_dataframe = create_label_mapping_dataframe(used_label_mapping, valid_dataset)
    label_mapping_dataframe.to_csv(OUTPUT_DIR / "label_mapping.csv", index=False)

    # Create a reproducible balanced stratified split whenever possible.
    training_indices, validation_indices, split_method = balanced_stratified_split_indices(y)

    X_training = X[training_indices]
    y_training = y[training_indices]
    training_image_names = valid_image_names[training_indices]

    X_validation = X[validation_indices]
    y_validation = y[validation_indices]
    validation_image_names = valid_image_names[validation_indices]

    if len(X_training) == 0 or len(X_validation) == 0:
        fail("The train/validation split produced an empty set. More valid images are required.")

    # Save split outputs.
    np.save(OUTPUT_DIR / "X_training.npy", X_training)
    np.save(OUTPUT_DIR / "y_training.npy", y_training)
    np.save(OUTPUT_DIR / "training_image_names.npy", training_image_names)

    np.save(OUTPUT_DIR / "X_validation.npy", X_validation)
    np.save(OUTPUT_DIR / "y_validation.npy", y_validation)
    np.save(OUTPUT_DIR / "validation_image_names.npy", validation_image_names)

    training_dataset = valid_dataset.iloc[training_indices].reset_index(drop=True)
    validation_dataset = valid_dataset.iloc[validation_indices].reset_index(drop=True)

    training_dataset.to_csv(OUTPUT_DIR / "training_dataset.csv", index=False)
    validation_dataset.to_csv(OUTPUT_DIR / "validation_dataset.csv", index=False)

    # Print only the compact final summary.
    print_compact_summary(
        total_rows=total_rows,
        warning_summary_dataframe=warning_summary_dataframe,
        valid_dataset=valid_dataset,
        X=X,
        y=y,
        training_dataset=training_dataset,
        validation_dataset=validation_dataset,
        X_training=X_training,
        X_validation=X_validation,
        split_method=split_method,
        output_dir=OUTPUT_DIR,
    )


if __name__ == "__main__":
    main()
